assert.deepEqual(MATCH_FORMATS.novice_45sec.periods.map(p => p.seconds), [45, 45, 45]);
assert.deepEqual(MATCH_FORMATS.youth_1min.periods.map(p => p.seconds), [60, 60, 60]);
assert.deepEqual(MATCH_FORMATS.jv_90sec.periods.map(p => p.seconds), [90, 90, 90]);
assert.deepEqual(MATCH_FORMATS.jv_consolation.periods.map(p => p.seconds), [60, 90, 90]);
assert.deepEqual(MATCH_FORMATS.varsity_championship.periods.map(p => p.seconds), [120, 120, 120]);
assert.deepEqual(MATCH_FORMATS.varsity_consolation.periods.map(p => p.seconds), [60, 120, 120]);
assert.deepEqual(MATCH_FORMATS.college_3_2_2.periods.map(p => p.seconds), [180, 120, 120]);

const state = createMatchState("novice_45sec");
assert.equal(state.time, 45);
assert.equal(isValidAction("neutral", "athlete", "esc1"), false);
assert.equal(isValidAction("neutral", "athlete", "td3"), true);
applyScore(state, "athlete", 3);
updatePositionAfterScore(state, "athlete", "td3");
assert.equal(state.athleteScore, 3);
assert.equal(state.position, "green_top");
applyScore(state, "opponent", 1);
updatePositionAfterScore(state, "opponent", "esc1");
assert.equal(state.position, "neutral");
undoScore(state, "opponent", 1);
assert.equal(state.opponentScore, 0);

state.currentRound = "1";
let round = advanceRound(state);
assert.equal(round.round, "2");
assert.equal(round.requiresChoice, true);
setSecondPeriodFirstChooser(state, "athlete");
assert.equal(applyRoundChoice(state, "defer"), true);
assert.equal(state.pendingChoice.chooser, "opponent");
assert.equal(applyRoundChoice(state, "bottom"), true);
state.currentRound = "2";
round = advanceRound(state);
assert.equal(round.round, "3");
assert.equal(round.chooser, "athlete");

const tied = createMatchState();
tied.currentRound = "3";
assert.equal(advanceRound(tied).round, "SV1");
tied.currentRound = "SV1";
assert.equal(advanceRound(tied).round, "TB1");
tied.currentRound = "TB1";
assert.equal(advanceRound(tied).round, "TB2");
tied.currentRound = "TB2";
assert.equal(advanceRound(tied).round, "UTB");

assert.equal(validateFinalResult({ athleteScore: 0, opponentScore: 0 }, "athlete", "tech").valid, false);
assert.equal(validateFinalResult({ athleteScore: 7, opponentScore: 0 }, "athlete", "decision").valid, true);
assert.equal(validateFinalResult({ athleteScore: 8, opponentScore: 0 }, "athlete", "major").valid, true);
assert.equal(validateFinalResult({ athleteScore: 15, opponentScore: 0 }, "athlete", "tech").valid, true);
assert.equal(validateFinalResult({ athleteScore: 15, opponentScore: 0 }, "opponent", "tech").valid, false);
assert.equal(validateFinalResult({ athleteScore: 0, opponentScore: 0 }, "athlete", "pin").valid, true);

const refState = createMatchState();
