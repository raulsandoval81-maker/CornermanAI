import assert from "node:assert/strict";
import { MATCH_FORMATS } from "../shared/match-formats.js";
import { createMatchState, applyRoundChoice, advanceRound, applyScore, undoScore, setSecondPeriodFirstChooser } from "../shared/match-state.js";
import { isValidAction, updatePositionAfterScore } from "../console/modules/match-scoring.js";
